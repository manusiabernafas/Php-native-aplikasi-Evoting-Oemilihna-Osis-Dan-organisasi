CREATE DATABASE IF NOT EXISTS e_voting CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE e_voting;

DROP TABLE IF EXISTS suara;
DROP TABLE IF EXISTS pemilih;
DROP TABLE IF EXISTS kandidat;
DROP TABLE IF EXISTS pemilihan;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS pengaturan;

CREATE TABLE pengaturan (
  id INT PRIMARY KEY,
  nama_instansi VARCHAR(120) NOT NULL,
  hasil_publik TINYINT(1) NOT NULL DEFAULT 0   -- 1 = hasil bisa dilihat publik setelah pemilihan ditutup
) ENGINE=InnoDB;

CREATE TABLE users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(100) NOT NULL,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role ENUM('admin','panitia') NOT NULL DEFAULT 'panitia'
) ENGINE=InnoDB;

CREATE TABLE pemilihan (
  id INT AUTO_INCREMENT PRIMARY KEY,
  judul VARCHAR(150) NOT NULL,
  mulai DATETIME NOT NULL,
  selesai DATETIME NOT NULL,
  aktif TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB;

CREATE TABLE kandidat (
  id INT AUTO_INCREMENT PRIMARY KEY,
  pemilihan_id INT NOT NULL,
  no_urut TINYINT NOT NULL,
  ketua VARCHAR(100) NOT NULL,
  kelas_ketua VARCHAR(20),
  wakil VARCHAR(100),
  kelas_wakil VARCHAR(20),
  visi TEXT,
  misi TEXT,
  foto VARCHAR(100),
  UNIQUE KEY uk_no (pemilihan_id, no_urut),
  FOREIGN KEY (pemilihan_id) REFERENCES pemilihan(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Daftar pemilih tetap (DPT). Kolom sudah_memilih menandai pemilih yang sudah menggunakan haknya,
-- TETAPI tidak menyimpan pilihannya.
CREATE TABLE pemilih (
  id INT AUTO_INCREMENT PRIMARY KEY,
  pemilihan_id INT NOT NULL,
  nis VARCHAR(20) NOT NULL,
  nama VARCHAR(100) NOT NULL,
  kelas VARCHAR(20) NOT NULL,
  token CHAR(6) NOT NULL,
  sudah_memilih TINYINT(1) NOT NULL DEFAULT 0,
  waktu_memilih DATETIME NULL,
  UNIQUE KEY uk_nis (pemilihan_id, nis),
  UNIQUE KEY uk_token (pemilihan_id, token),
  INDEX (kelas),
  FOREIGN KEY (pemilihan_id) REFERENCES pemilihan(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Kotak suara: TIDAK ada kolom pemilih_id. ID acak (bukan auto increment) dan waktu
-- dibulatkan ke jam, sehingga suara tidak bisa dicocokkan dengan urutan/jam pemilih.
CREATE TABLE suara (
  id CHAR(32) PRIMARY KEY,
  pemilihan_id INT NOT NULL,
  kandidat_id INT NOT NULL,
  jam DATETIME NOT NULL,
  INDEX (pemilihan_id, kandidat_id),
  FOREIGN KEY (pemilihan_id) REFERENCES pemilihan(id) ON DELETE CASCADE,
  FOREIGN KEY (kandidat_id) REFERENCES kandidat(id) ON DELETE CASCADE
) ENGINE=InnoDB;

